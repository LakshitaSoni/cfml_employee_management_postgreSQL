-- =============================================================================
-- Employee Management System - schema (PostgreSQL 11+)
--
-- Safe to run repeatedly (idempotent): every object is created only if missing,
-- and existing rows are never modified or dropped.
--
-- HOW TO RUN (pgAdmin 4)
--   1. Create the database once (Databases > Create > Database...), or run this
--      while connected to the default "postgres" database:
--          CREATE DATABASE admin_employee_management;
--   2. In the tree, select the admin_employee_management database, then open
--      Tools > Query Tool, paste this whole file and press F5 (Execute).
--
-- HOW TO RUN (psql)
--   psql -U postgres -h 127.0.0.1 -d admin_employee_management -f database/schema.sql
-- =============================================================================

CREATE TABLE IF NOT EXISTS employees (
    id            INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100)  NOT NULL,
    email         VARCHAR(254)  NOT NULL,
    phone         VARCHAR(30),
    department    VARCHAR(100)  NOT NULL,
    job_title     VARCHAR(100),
    salary        NUMERIC(12,2),
    joining_date  DATE,
    status        VARCHAR(10)   NOT NULL DEFAULT 'Active',
    created_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_employees_email   UNIQUE (email),
    CONSTRAINT chk_employees_status CHECK (status IN ('Active', 'On Leave', 'Inactive'))
);

-- -----------------------------------------------------------------------------
-- Indexes
-- -----------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_employees_department   ON employees (department);
CREATE INDEX IF NOT EXISTS idx_employees_status       ON employees (status);
CREATE INDEX IF NOT EXISTS idx_employees_joining_date ON employees (joining_date);

-- -----------------------------------------------------------------------------
-- Keep updated_at current on every UPDATE (MySQL did this with ON UPDATE
-- CURRENT_TIMESTAMP; PostgreSQL needs a trigger).
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_employees_updated_at ON employees;
CREATE TRIGGER trg_employees_updated_at
    BEFORE UPDATE ON employees
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

